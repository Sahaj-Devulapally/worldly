def region(x):
    if x['region'] == 'Americas':
        return 'South America' if x['subregion'] == 'South America' else 'North America'
    return x['region']

out = []
for x in sel:
    code = x['cca2']
    name = NAME_FIX.get(code, x['name']['common'])
    caps, cap_alts = CAPITAL_FIX.get(code, (x['capital'], []))
    alts = {x['name']['common'], x['name']['official']} | set(EXTRA_NAMES.get(code, []))
    alts |= {a for a in x.get('altSpellings', []) if len(a) > 3 and not a.isupper()}
    alts.discard(name)
    out.append({
        'code': code.lower(), 'name': name, 'alt': sorted(alts),
        'capitals': caps, 'capAlt': cap_alts,
        'region': region(x), 'sub': x['subregion'],
    })
    src = os.path.join(dl, 'fi/package/flags/4x3', code.lower() + '.svg')
    os.makedirs(os.path.join(app, 'flags'), exist_ok=True)
    shutil.copy(src, os.path.join(app, 'flags', code.lower() + '.svg'))

out.sort(key=lambda c: c['name'])
with open(os.path.join(app, 'data.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by build.py. Source: world-countries (ODbL), flags: flag-icons (MIT).\n')
    f.write('const COUNTRIES = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')

# ---- Icons: a simple globe on a blue tile ----
def icon(size, maskable=False):
    S = size * 4
    im = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    bg = (30, 64, 175, 255)
    if maskable:
        d.rectangle([0, 0, S, S], fill=bg)
    else:
        d.rounded_rectangle([0, 0, S - 1, S - 1], radius=S * 0.22, fill=bg)
    cx = cy = S / 2
    r = S * (0.28 if maskable else 0.34)
    w = max(4, int(S * 0.028))
    line = (255, 255, 255, 255)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(56, 189, 248, 255), outline=line, width=w)
    for k in (0.45, 0.85):  # meridians
        d.ellipse([cx - r * k, cy - r, cx + r * k, cy + r], outline=line, width=w)
    d.line([cx, cy - r, cx, cy + r], fill=line, width=w)
    for t in (-0.5, 0, 0.5):  # parallels
        y = cy + r * t
        half = math.sqrt(max(0, r * r - (r * t) ** 2))
        d.line([cx - half, y, cx + half, y], fill=line, width=w)
    return im.resize((size, size), Image.LANCZOS)

os.makedirs(os.path.join(app, 'icons'), exist_ok=True)
for s in (192, 512):
    icon(s).save(os.path.join(app, 'icons', f'icon-{s}.png'))
icon(512, True).save(os.path.join(app, 'icons', 'icon-maskable-512.png'))
ati = icon(180, True)
ati.save(os.path.join(app, 'icons', 'apple-touch-icon.png'))
icon(32).save(os.path.join(app, 'icons', 'favicon-32.png'))
