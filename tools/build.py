"""Builds worldly/data.js, copies flags, and draws icons.
Usage: python3 -I build.py <download_dir> <app_dir>"""
import json, os, re, shutil, sys, math
from PIL import Image, ImageDraw

dl, app = sys.argv[1], sys.argv[2]
countries = json.load(open(os.path.join(dl, 'countries.json'), encoding='utf-8'))
sel = [x for x in countries if x.get('unMember') or x['cca2'] in ('VA', 'PS', 'TW', 'XK')]

